// DAT enum values matching the retail client.
namespace Acme.Dat {
    /// <summary>
    /// The AttributeId identifies a specific Character attribute.
    /// </summary>
    public enum AttributeId : uint {
        Strength = 0x01,

        Endurance = 0x02,

        Quickness = 0x03,

        Coordination = 0x04,

        Focus = 0x05,

        Self = 0x06,

    };
}
